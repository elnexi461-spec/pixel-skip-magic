CREATE TYPE public.app_role AS ENUM ('admin', 'user');
CREATE TYPE public.investment_status AS ENUM ('active', 'completed');
CREATE TYPE public.transaction_type AS ENUM ('deposit', 'withdrawal');
CREATE TYPE public.transaction_status AS ENUM ('pending', 'completed', 'rejected', 'failed');

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY,
  email text,
  phone text UNIQUE,
  display_name text,
  avatar_animal text NOT NULL DEFAULT 'cow',
  account_balance numeric(14,2) NOT NULL DEFAULT 0 CHECK (account_balance >= 0),
  deposit_balance numeric(14,2) NOT NULL DEFAULT 0 CHECK (deposit_balance >= 0),
  unclaimed_income numeric(14,2) NOT NULL DEFAULT 0 CHECK (unclaimed_income >= 0),
  available_points integer NOT NULL DEFAULT 0 CHECK (available_points >= 0),
  referral_code text NOT NULL UNIQUE DEFAULT upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8)),
  referred_by uuid,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE ON public.profiles TO authenticated;
GRANT ALL ON public.profiles TO service_role;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

